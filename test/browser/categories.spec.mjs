import {test,expect} from '@playwright/test';
import {readFile} from 'node:fs/promises';
import sharp from 'sharp';

test('el administrador selecciona el fondo de una categoría y puede quitarlo',async({page},testInfo)=>{
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/');
  const products=await (await page.request.get('/api/products')).json();
  const name=products[0].category;
  await page.getByRole('button',{name:'Iniciar sesión',exact:true}).click();
  await page.getByLabel('Correo electrónico',{exact:true}).fill('admin@example.com');
  await page.getByLabel('Contraseña',{exact:true}).fill('UI-exclusive-fixture-2026');
  await page.locator('#auth-form').getByRole('button',{name:'Iniciar sesión',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Hola, Administrador.'})).toBeVisible();
  await page.getByRole('link',{name:'Productos',exact:true}).click();
  await page.getByRole('button',{name:'Categorías',exact:true}).click();
  const categoryForm=async()=>{
    const categories=await (await page.request.get('/api/admin/categories')).json();
    return page.locator('.category-edit-form').nth(categories.findIndex(category=>category.name===name));
  };
  let form=await categoryForm();
  const image=await readFile(new URL('../../public/edg-universe-background.webp',import.meta.url));
  await form.locator('.category-image-input').setInputFiles({name:'categoria.webp',mimeType:'image/webp',buffer:image});
  await expect(form.locator('.category-image-preview img')).toBeVisible();
  await expect(form.locator('[name="image_id"]')).toHaveValue(/^[a-f0-9]{64}$/);
  await expect(form.getByRole('button',{name:'Guardar cambios',exact:true})).toBeEnabled();
  const imageId=await form.locator('[name="image_id"]').inputValue();
  await form.getByRole('button',{name:'Guardar cambios',exact:true}).click();
  await expect(page.locator('#toast')).toHaveText('Categoría guardada.');
  form=await categoryForm();
  await expect(form.locator('[name="image_id"]')).toHaveValue(imageId);
  await form.screenshot({path:testInfo.outputPath('category-image-editor.png')});
  await page.getByRole('button',{name:'Cerrar',exact:true}).click();
  await page.getByRole('link',{name:'Ver tienda ↗',exact:true}).click();
  const card=page.locator(`.category-tile[data-category=${JSON.stringify(name)}]`);
  await expect(card).toHaveClass(/has-image/);
  await expect(card.locator('img')).toHaveAttribute('src',`/media/${imageId}.jpg`);
  await card.scrollIntoViewIfNeeded();await card.locator('img').evaluate(image=>image.decode());
  await page.locator('.category-section').screenshot({path:testInfo.outputPath('category-cards-desktop.png')});
  await card.click();
  await expect(page.locator('#product-grid .product')).toHaveCount(products.filter(product=>product.category===name).length);
  await page.reload();
  await expect(card.locator('img')).toHaveAttribute('src',`/media/${imageId}.jpg`);
  await page.setViewportSize({width:390,height:844});
  await page.goto('/');await expect(card).toHaveClass(/has-image/);
  await card.scrollIntoViewIfNeeded();await card.locator('img').evaluate(image=>image.decode());
  await page.locator('.category-section').screenshot({path:testInfo.outputPath('category-cards-mobile.png')});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);

  await page.goto('/#products');
  await page.getByRole('button',{name:'Categorías',exact:true}).click();
  form=await categoryForm();
  const replacement=await sharp({create:{width:32,height:32,channels:3,background:'#225577'}}).png().toBuffer();
  await page.route('**/api/admin/media',route=>route.fulfill({status:500,json:{error:'No se pudo subir la imagen.'}}));
  await form.locator('.category-image-input').setInputFiles({name:'replacement.png',mimeType:'image/png',buffer:replacement});
  await expect(page.locator('#toast')).toHaveText('No se pudo subir la imagen.');
  await expect(form.locator('[name="image_id"]')).toHaveValue(imageId);
  await expect(form.getByRole('button',{name:'Guardar cambios',exact:true})).toBeEnabled();
  await page.unroute('**/api/admin/media');
  await form.getByRole('button',{name:'Quitar imagen',exact:true}).click();
  await expect(form.locator('.category-image-preview img')).toHaveCount(0);
  await form.getByRole('button',{name:'Guardar cambios',exact:true}).click();
  await expect(page.locator('#toast')).toHaveText('Categoría guardada.');
  await page.getByRole('button',{name:'Cerrar',exact:true}).click();
  await page.getByRole('link',{name:'Ver tienda ↗',exact:true}).click();
  await expect(card).not.toHaveClass(/has-image/);
  await expect(card.locator('img')).toHaveCount(0);
  expect(errors).toEqual([]);
});

test('guardar una categoría conserva el borrador y la subida de otra',async({page})=>{
  await page.goto('/');
  await page.getByRole('button',{name:'Iniciar sesión',exact:true}).click();
  await page.getByLabel('Correo electrónico',{exact:true}).fill('admin@example.com');
  await page.getByLabel('Contraseña',{exact:true}).fill('UI-exclusive-fixture-2026');
  await page.locator('#auth-form').getByRole('button',{name:'Iniciar sesión',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Hola, Administrador.'})).toBeVisible();
  await page.getByRole('link',{name:'Productos',exact:true}).click();
  await page.getByRole('button',{name:'Categorías',exact:true}).click();
  const forms=page.locator('.category-edit-form'),first=forms.nth(0),second=forms.nth(1);
  await second.getByLabel('Categoría',{exact:true}).fill('Nombre en borrador');
  let release;
  const gate=new Promise(resolve=>release=resolve);
  await page.route('**/api/admin/media',async route=>{await gate;await route.continue();});
  const image=await sharp({create:{width:32,height:32,channels:3,background:'#557722'}}).png().toBuffer();
  await second.locator('.category-image-input').setInputFiles({name:'draft.png',mimeType:'image/png',buffer:image});
  await expect(second.getByRole('button',{name:'Guardar cambios',exact:true})).toBeDisabled();
  await first.getByRole('button',{name:'Guardar cambios',exact:true}).click();
  await expect(page.locator('#toast')).toHaveText('Categoría guardada.');
  await expect(second.getByLabel('Categoría',{exact:true})).toHaveValue('Nombre en borrador');
  release();
  await expect(second.locator('[name="image_id"]')).toHaveValue(/^[a-f0-9]{64}$/);
  const imageId=await second.locator('[name="image_id"]').inputValue();
  await first.getByRole('button',{name:'Guardar cambios',exact:true}).click();
  await expect(page.locator('#toast')).toHaveText('Categoría guardada.');
  await expect(second.getByLabel('Categoría',{exact:true})).toHaveValue('Nombre en borrador');
  await expect(second.locator('[name="image_id"]')).toHaveValue(imageId);
});
